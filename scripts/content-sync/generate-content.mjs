#!/usr/bin/env node
// Regenerates the app's content from Contenido_Guia_Ancianos.xlsx (project root):
//
//   src/content/generated/<packId>.ts   one card array per pack
//   src/content/packs.ts                PACKS, ALL_CARDS, PACKS_BY_ID, CARDS_BY_ID, getCardsForPack
//   src/content/quiz.ts                 QUIZ (multiple-choice bank for the Simulacro)
//   src/content/uiText.ts               UI_TEXT (every on-screen string)
//
// The spreadsheet is the source of truth. This runs automatically before
// `npm start` / `npm run android|ios|web` (package.json "pre*" hooks) and can
// be run by hand:
//
//   npm run sync-content          regenerate
//   npm run check-content         exit 1 if generated files are out of date (CI)
//
// Plain Node + the `xlsx` package only. See scripts/content-sync/README.md.
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync, unlinkSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import XLSX from "xlsx";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..", "..");
const XLSX_NAME = "Contenido_Guia_Ancianos.xlsx";
const XLSX_PATH = path.join(ROOT, XLSX_NAME);
const CONTENT_DIR = path.join(ROOT, "src", "content");
const GEN_DIR = path.join(CONTENT_DIR, "generated");
const PACKS_TS = path.join(CONTENT_DIR, "packs.ts");
const QUIZ_TS = path.join(CONTENT_DIR, "quiz.ts");
const UI_TEXT_TS = path.join(CONTENT_DIR, "uiText.ts");

const CHECK_ONLY = process.argv.includes("--check");
const GENERATED_MARKER = "// AUTO-GENERATED by scripts/content-sync/generate-content.mjs";
const BANNER =
  `${GENERATED_MARKER} from\n` +
  `// ${XLSX_NAME} — do not hand-edit. Edit the spreadsheet instead\n` +
  `// (it regenerates automatically before npm start — see scripts/content-sync/README.md).\n`;

const CATEGORIES = new Set(["guia", "orden", "cfw", "biblia"]);
const ID_RE = /^[a-z][a-z0-9-]*$/;
const PACK_ID_RE = /^[a-z][a-z0-9]*$/;
const UI_KEY_RE = /^[a-zA-Z][a-zA-Z0-9]*(\.[a-zA-Z][a-zA-Z0-9]*)*$/;

const errors = [];
const fail = (msg) => errors.push(msg);

function esc(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, "\\n");
}
const str = (v) => (v === undefined || v === null ? "" : String(v).trim());
const truthy = (v) => str(v).toUpperCase() === "TRUE";

function sheetToObjects(wb, name) {
  const ws = wb.Sheets[name];
  if (!ws) {
    fail(`Missing "${name}" tab.`);
    return [];
  }
  const rows = XLSX.utils.sheet_to_json(ws, { header: 1, defval: "" });
  if (rows.length === 0) return [];
  const headers = rows[0].map((h) => str(h));
  return rows
    .slice(1)
    .map((r, i) => ({ r, rowNum: i + 2 }))
    .filter(({ r }) => r.some((c) => str(c) !== ""))
    .map(({ r, rowNum }) => {
      const obj = { __row: rowNum };
      headers.forEach((h, i) => (obj[h] = r[i] === undefined ? "" : r[i]));
      return obj;
    });
}

function parsePacks(wb) {
  const seen = new Set();
  return sheetToObjects(wb, "Packs")
    .filter((r) => str(r["Pack ID"]))
    .map((r) => {
      const where = `Packs row ${r.__row}`;
      const p = {
        id: str(r["Pack ID"]),
        category: str(r["Category"]),
        title: str(r["Title"]),
        description: str(r["Description"]),
        color: str(r["Color (hex)"]),
        visible: str(r["Visible?"]) === "" ? true : truthy(r["Visible?"]),
      };
      if (!PACK_ID_RE.test(p.id)) fail(`${where}: Pack ID '${p.id}' must be lowercase letters/digits.`);
      if (seen.has(p.id)) fail(`${where}: duplicate Pack ID '${p.id}'.`);
      seen.add(p.id);
      if (!CATEGORIES.has(p.category)) fail(`${where}: Category must be one of ${[...CATEGORIES].join(", ")}.`);
      if (!p.title) fail(`${where}: missing Title.`);
      if (!/^#[0-9a-fA-F]{6}$/.test(p.color)) fail(`${where}: Color (hex) must look like #1A2B3C.`);
      return p;
    });
}

function parseCards(wb, packIds) {
  const seenIds = new Set();
  const cardsByPack = {};
  for (const r of sheetToObjects(wb, "Cards")) {
    const where = `Cards row ${r.__row}`;
    const packId = str(r["Pack ID"]);
    if (!packId) continue;
    const id = str(r["Card ID"]);
    const front = str(r["Front (Question)"]);
    const backText = str(r["Back (Answer)"]);
    if (!packIds.has(packId)) fail(`${where}: Pack ID '${packId}' isn't on the Packs tab.`);
    if (!ID_RE.test(id)) fail(`${where}: Card ID '${id}' must be lowercase letters, digits and dashes.`);
    if (seenIds.has(id)) fail(`${where}: duplicate Card ID '${id}'.`);
    seenIds.add(id);
    if (!front) fail(`${where}: card '${id}' has no Front.`);
    if (!backText) fail(`${where}: card '${id}' has no Back.`);
    const quote = str(r["Source Quote"]);
    const location = str(r["Source Location"]);
    if (quote && !location) fail(`${where}: card '${id}' has a Source Quote but no Source Location.`);
    if (location && !quote) fail(`${where}: card '${id}' has a Source Location but no Source Quote.`);
    (cardsByPack[packId] ||= []).push({
      id,
      packId,
      front: front,
      back: backText,
      note: str(r["Back Note"]) || null,
      ref: str(r["Reference"]) || null,
      source: quote ? { quote, location } : null,
    });
  }
  return cardsByPack;
}

function parseQuiz(wb, packIds) {
  const seenIds = new Set();
  const out = [];
  for (const r of sheetToObjects(wb, "Quiz")) {
    const where = `Quiz row ${r.__row}`;
    const packId = str(r["Pack ID"]);
    if (!packId) continue;
    const q = {
      id: str(r["Question ID"]),
      packId,
      question: str(r["Question"]),
      correct: str(r["Correct Answer"]),
      wrong: [str(r["Wrong 1"]), str(r["Wrong 2"]), str(r["Wrong 3"])],
      ref: str(r["Reference"]) || null,
    };
    if (!packIds.has(packId)) fail(`${where}: Pack ID '${packId}' isn't on the Packs tab.`);
    if (!ID_RE.test(q.id)) fail(`${where}: Question ID '${q.id}' must be lowercase letters, digits and dashes.`);
    if (seenIds.has(q.id)) fail(`${where}: duplicate Question ID '${q.id}'.`);
    seenIds.add(q.id);
    if (!q.question) fail(`${where}: question '${q.id}' has no Question text.`);
    if (!q.correct) fail(`${where}: question '${q.id}' has no Correct Answer.`);
    if (q.wrong.some((w) => !w)) fail(`${where}: question '${q.id}' needs all three Wrong answers.`);
    const all = [q.correct, ...q.wrong].map((s) => s.toLowerCase());
    if (new Set(all).size !== 4) fail(`${where}: question '${q.id}' has duplicate options.`);
    out.push(q);
  }
  return out;
}

function parseUiText(wb) {
  const out = {};
  for (const r of sheetToObjects(wb, "UI Text")) {
    const key = str(r["Key"]);
    if (!key) continue;
    const text = str(r["Text"]);
    if (!UI_KEY_RE.test(key)) fail(`UI Text row ${r.__row}: key '${key}' isn't a dotted identifier.`);
    if (key in out) fail(`UI Text row ${r.__row}: duplicate key '${key}'.`);
    if (!text) fail(`UI Text row ${r.__row}: key '${key}' has no Text.`);
    out[key] = text;
  }
  return out;
}

const constName = (packId) => `${packId}Cards`;

function renderCard(c) {
  const back = [`text: "${esc(c.back)}"`];
  if (c.note) back.push(`note: "${esc(c.note)}"`);
  if (c.ref) back.push(`ref: "${esc(c.ref)}"`);
  if (c.source) back.push(`source: { quote: "${esc(c.source.quote)}", location: "${esc(c.source.location)}" }`);
  return [
    "  {",
    `    id: "${esc(c.id)}",`,
    `    packId: "${esc(c.packId)}",`,
    `    front: { text: "${esc(c.front)}" },`,
    `    back: { ${back.join(", ")} },`,
    "  },",
  ].join("\n");
}

function renderPackFile(pack, cards) {
  return (
    BANNER +
    `import type { Card } from "../types";\n\n` +
    `// ${pack.title} — ${cards.length} cards.\n` +
    `export const ${constName(pack.id)}: Card[] = [\n${cards.map(renderCard).join("\n")}\n];\n`
  );
}

function renderPacksTs(packs) {
  const imports = packs.map((p) => `import { ${constName(p.id)} } from "./generated/${p.id}";`).join("\n");
  const entries = packs
    .map(
      (p) =>
        `  pack({\n` +
        `    id: "${esc(p.id)}",\n` +
        `    title: "${esc(p.title)}",\n` +
        `    description: "${esc(p.description)}",\n` +
        `    category: "${p.category}",\n` +
        `    visible: ${p.visible},\n` +
        `    color: "${esc(p.color)}",\n` +
        `    cards: ${constName(p.id)},\n` +
        `  }),`
    )
    .join("\n");
  return (
    BANNER +
    `import type { Card, Pack } from "./types";\n${imports}\n\n` +
    `function pack(def: Omit<Pack, "cardIds"> & { cards: Card[] }): Pack {\n` +
    `  const { cards, ...rest } = def;\n` +
    `  return { ...rest, cardIds: cards.map((c) => c.id) };\n` +
    `}\n\n` +
    `export const PACKS: Pack[] = [\n${entries}\n];\n\n` +
    `export const ALL_CARDS: Card[] = [\n${packs.map((p) => `  ...${constName(p.id)},`).join("\n")}\n];\n\n` +
    `export const PACKS_BY_ID: Record<string, Pack> = Object.fromEntries(PACKS.map((p) => [p.id, p]));\n\n` +
    `export const CARDS_BY_ID: Record<string, Card> = Object.fromEntries(ALL_CARDS.map((c) => [c.id, c]));\n\n` +
    `/** Every card in a pack, in spreadsheet order. */\n` +
    `export function getCardsForPack(packId: string): Card[] {\n` +
    `  return (PACKS_BY_ID[packId]?.cardIds ?? []).map((id) => CARDS_BY_ID[id]);\n` +
    `}\n`
  );
}

function renderQuizTs(quiz) {
  const body = quiz
    .map((q) => {
      const lines = [
        "  {",
        `    id: "${esc(q.id)}",`,
        `    packId: "${esc(q.packId)}",`,
        `    question: "${esc(q.question)}",`,
        `    correct: "${esc(q.correct)}",`,
        `    wrong: [${q.wrong.map((w) => `"${esc(w)}"`).join(", ")}],`,
      ];
      if (q.ref) lines.push(`    ref: "${esc(q.ref)}",`);
      lines.push("  },");
      return lines.join("\n");
    })
    .join("\n");
  return (
    BANNER +
    `import type { QuizQuestion } from "./types";\n\n` +
    `// ${quiz.length} multiple-choice questions for the Simulacro.\n` +
    `export const QUIZ: QuizQuestion[] = [\n${body}\n];\n`
  );
}

function renderUiText(ui) {
  const body = Object.entries(ui)
    .map(([k, v]) => `  "${esc(k)}": "${esc(v)}",`)
    .join("\n");
  return BANNER + `export const UI_TEXT: Record<string, string> = {\n${body}\n};\n`;
}

function main() {
  if (!existsSync(XLSX_PATH)) {
    console.error(`No ${XLSX_NAME} at ${XLSX_PATH} — skipping content generation.`);
    process.exit(0);
  }
  const wb = XLSX.readFile(XLSX_PATH);
  const packs = parsePacks(wb);
  const packIds = new Set(packs.map((p) => p.id));
  const cardsByPack = parseCards(wb, packIds);
  const quiz = parseQuiz(wb, packIds);
  const ui = parseUiText(wb);
  for (const p of packs) if (!(cardsByPack[p.id] || []).length) fail(`Pack '${p.id}' has no cards.`);

  if (errors.length) {
    console.error(`${XLSX_NAME} has ${errors.length} problem(s):\n  - ${errors.join("\n  - ")}`);
    process.exit(1);
  }

  const outputs = new Map();
  for (const p of packs) outputs.set(path.join(GEN_DIR, `${p.id}.ts`), renderPackFile(p, cardsByPack[p.id]));
  outputs.set(PACKS_TS, renderPacksTs(packs));
  outputs.set(QUIZ_TS, renderQuizTs(quiz));
  outputs.set(UI_TEXT_TS, renderUiText(ui));

  // Generated pack files for packs no longer in the sheet. Only files that
  // carry the generated marker are ever touched.
  const stale = existsSync(GEN_DIR)
    ? readdirSync(GEN_DIR)
        .filter((f) => f.endsWith(".ts"))
        .map((f) => path.join(GEN_DIR, f))
        .filter((f) => !outputs.has(f) && readFileSync(f, "utf8").startsWith(GENERATED_MARKER))
    : [];

  const changed = [...outputs].filter(([f, content]) => !existsSync(f) || readFileSync(f, "utf8") !== content);

  if (CHECK_ONLY) {
    if (changed.length || stale.length) {
      console.error(
        `Generated content is out of date (${changed.length + stale.length} file(s)). Run: npm run sync-content`
      );
      process.exit(1);
    }
    console.log(`Generated content matches ${XLSX_NAME}.`);
    return;
  }

  mkdirSync(GEN_DIR, { recursive: true });
  for (const [f, content] of changed) writeFileSync(f, content);
  for (const f of stale) unlinkSync(f);

  const cardCount = Object.values(cardsByPack).reduce((n, cs) => n + cs.length, 0);
  if (changed.length || stale.length) {
    console.log(
      `Content synced: ${packs.length} packs, ${cardCount} cards, ${quiz.length} quiz questions, ` +
        `${Object.keys(ui).length} UI strings (${changed.length} file(s) written, ${stale.length} removed).`
    );
  } else {
    console.log(`Content already matches ${XLSX_NAME} — nothing to do.`);
  }
}

main();
