#!/usr/bin/env node
// Regenerates the app's content from Contenido_Guia_Ancianos.xlsx (project root):
//
//   src/content/course.ts      COURSE (Home layout), PACKS, PACKS_BY_ID — readings + question packs
//   src/content/questions.ts   QUESTIONS, QUESTIONS_BY_ID, getQuestionsForPack — the multiple-choice bank
//   src/content/uiText.ts      UI_TEXT (every on-screen string)
//   src/content/videos.ts      VIDEOS (the Home video cards; files in media/videos/)
//
// The spreadsheet is the source of truth. This runs automatically before
// `npm start` / `npm run android|ios|web` (package.json "pre*" hooks) and can
// be run by hand:
//
//   npm run sync-content          regenerate
//   npm run check-content         exit 1 if generated files are out of date (CI)
//
// Plain Node + the `xlsx` package only. See scripts/content-sync/README.md.
import { readFileSync, writeFileSync, existsSync, unlinkSync, readdirSync, rmdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import XLSX from "xlsx";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..", "..");
const XLSX_NAME = "Contenido_Guia_Ancianos.xlsx";
const XLSX_PATH = path.join(ROOT, XLSX_NAME);
const CONTENT_DIR = path.join(ROOT, "src", "content");
const DOCS_DIR = path.join(CONTENT_DIR, "documents");
const COURSE_TS = path.join(CONTENT_DIR, "course.ts");
const QUESTIONS_TS = path.join(CONTENT_DIR, "questions.ts");
const UI_TEXT_TS = path.join(CONTENT_DIR, "uiText.ts");
const VIDEOS_TS = path.join(CONTENT_DIR, "videos.ts");
const VIDEO_DIR = path.join(ROOT, "media", "videos");
const POSTER_DIR = path.join(VIDEO_DIR, "posters");
// Outputs of the flash-card era, removed if still present (only when they
// carry the generated marker).
const LEGACY = [path.join(CONTENT_DIR, "packs.ts"), path.join(CONTENT_DIR, "quiz.ts")];
const LEGACY_DIR = path.join(CONTENT_DIR, "generated");

const CHECK_ONLY = process.argv.includes("--check");
const GENERATED_MARKER = "// AUTO-GENERATED by scripts/content-sync/generate-content.mjs";
const BANNER =
  `${GENERATED_MARKER} from\n` +
  `// ${XLSX_NAME} — do not hand-edit. Edit the spreadsheet instead\n` +
  `// (it regenerates automatically before npm start — see scripts/content-sync/README.md).\n`;

const DOCUMENTS = ["guia", "confesion", "orden"];
const ID_RE = /^[a-z][a-z0-9-]*$/;
const PACK_ID_RE = /^[a-z][a-z0-9]*$/;
const UI_KEY_RE = /^[a-zA-Z][a-zA-Z0-9]*(\.[a-zA-Z][a-zA-Z0-9]*)*$/;
// Content-over-trivia rule for question wording (see the Read Me tab).
const TRIVIA_RE = /(en qu[eé] (vers[ií]culo|cap[ií]tulo|secci[oó]n|p[aá]rrafo)|cu[aá]nt[oa]s (votos|cap[ií]tulos|secciones|vers[ií]culos|art[ií]culos))/i;

const errors = [];
const fail = (msg) => errors.push(msg);

const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, "\\n");
const str = (v) => (v === undefined || v === null ? "" : String(v).trim());
const truthy = (v) => str(v).toUpperCase() === "TRUE";
const visibleCol = (v) => (str(v) === "" ? true : truthy(v));

function sheetToObjects(wb, name) {
  const ws = wb.Sheets[name];
  if (!ws) {
    fail(`Missing "${name}" tab.`);
    return [];
  }
  const rows = XLSX.utils.sheet_to_json(ws, { header: 1, defval: "" });
  if (rows.length === 0) return [];
  const headers = rows[0].map((h) => str(h));
  return rows
    .slice(1)
    .map((r, i) => ({ r, rowNum: i + 2 }))
    .filter(({ r }) => r.some((c) => str(c) !== ""))
    .map(({ r, rowNum }) => {
      const obj = { __row: rowNum };
      headers.forEach((h, i) => (obj[h] = r[i] === undefined ? "" : r[i]));
      return obj;
    });
}

/** docId -> [{ id, title, part, partIndex, partSize }] in reading order. */
function loadDocumentChapters() {
  const out = {};
  for (const id of DOCUMENTS) {
    const file = path.join(DOCS_DIR, `${id}.json`);
    if (!existsSync(file)) {
      fail(`Missing ${path.relative(ROOT, file)} (see scripts/documents/).`);
      out[id] = [];
      continue;
    }
    const doc = JSON.parse(readFileSync(file, "utf8"));
    out[id] = doc.parts.flatMap((p) =>
      p.chapters.map((c, i) => ({ id: c.id, title: c.title, part: p.title, partIndex: i + 1, partSize: p.chapters.length }))
    );
  }
  return out;
}

// "Capítulo 3 · Del decreto eterno de Dios" -> "Del decreto eterno de Dios"
const shortChapterTitle = (title) => title.replace(/^Cap[ií]tulo \d+ · /, "");

/** The line under a Lectura's title on Home. The Guía's chapters are long
 *  sections inside a few big parts, so it names the part and the section
 *  numbers ("La iglesia y el rol del anciano: secciones 1–5"); the Confesión
 *  lists its (short) chapter titles; the Libro de orden has none (its titles,
 *  "Capítulos 1–4" under a book sub-heading, already say it). */
function readingSubtitle(docId, included) {
  if (docId === "orden") return "";
  if (docId !== "guia") return included.map((c) => shortChapterTitle(c.title)).join(" · ");
  const byPart = [];
  for (const c of included) {
    const last = byPart[byPart.length - 1];
    if (last && last.part === c.part) last.items.push(c);
    else byPart.push({ part: c.part, items: [c] });
  }
  return byPart
    .map(({ part, items }) => {
      if (items[0].partSize === 1) return part;
      const a = items[0].partIndex;
      const b = items[items.length - 1].partIndex;
      return a === b ? `${part}: sección ${a}` : `${part}: secciones ${a}–${b}`;
    })
    .join(" · ");
}

function parseCourse(wb, chapters) {
  const seen = new Set();
  const packs = [];
  for (const r of sheetToObjects(wb, "Course")) {
    const id = str(r["ID"]);
    if (!id) continue;
    const where = `Course row ${r.__row}`;
    const docId = str(r["Document"]);
    const readingTitle = str(r["Reading Title"]);
    const p = {
      id,
      section: str(r["Section"]),
      subsection: str(r["Subsection"]),
      title: str(r["Questions Title"]),
      description: str(r["Description"]),
      color: str(r["Color (hex)"]),
      visible: visibleCol(r["Visible?"]),
      category: docId || "biblia",
      reading: null,
    };
    if (!PACK_ID_RE.test(id)) fail(`${where}: ID '${id}' must be lowercase letters/digits.`);
    if (seen.has(id)) fail(`${where}: duplicate ID '${id}'.`);
    seen.add(id);
    if (!p.section) fail(`${where}: missing Section.`);
    if (!p.title) fail(`${where}: missing Questions Title.`);
    if (!/^#[0-9a-fA-F]{6}$/.test(p.color)) fail(`${where}: Color (hex) must look like #1A2B3C.`);
    if (readingTitle || docId) {
      if (!readingTitle) fail(`${where}: has a Document but no Reading Title.`);
      if (!DOCUMENTS.includes(docId)) fail(`${where}: Document must be one of ${DOCUMENTS.join(", ")}.`);
      const list = chapters[docId] || [];
      const a = list.findIndex((c) => c.id === str(r["First Chapter"]));
      const b = list.findIndex((c) => c.id === str(r["Last Chapter"]));
      if (a < 0) fail(`${where}: First Chapter '${str(r["First Chapter"])}' isn't a chapter of ${docId}.`);
      if (b < 0) fail(`${where}: Last Chapter '${str(r["Last Chapter"])}' isn't a chapter of ${docId}.`);
      if (a >= 0 && b >= 0 && b < a) fail(`${where}: Last Chapter comes before First Chapter.`);
      const included = a >= 0 && b >= a ? list.slice(a, b + 1) : [];
      p.reading = {
        title: readingTitle,
        docId,
        chapterIds: included.map((c) => c.id),
        subtitle: readingSubtitle(docId, included),
      };
    }
    packs.push(p);
  }
  // A section's rows must be contiguous, as must a subsection's within it.
  const sectionsSeen = [];
  for (const p of packs) {
    const key = `${p.section}\u0000${p.subsection}`;
    const last = sectionsSeen[sectionsSeen.length - 1];
    if (last !== key) {
      if (sectionsSeen.includes(key)) fail(`Course: rows for "${p.section}${p.subsection ? " › " + p.subsection : ""}" must be next to each other.`);
      sectionsSeen.push(key);
    }
  }
  return packs;
}

function parseQuestions(wb, packIds) {
  const seenIds = new Set();
  const out = [];
  for (const r of sheetToObjects(wb, "Questions")) {
    const where = `Questions row ${r.__row}`;
    const packId = str(r["Pack ID"]);
    if (!packId) continue;
    const q = {
      id: str(r["Question ID"]),
      packId,
      question: str(r["Question"]),
      correct: str(r["Correct Answer"]),
      wrong: [str(r["Wrong 1"]), str(r["Wrong 2"]), str(r["Wrong 3"])],
      explanation: str(r["Explanation"]) || null,
      ref: str(r["Reference"]) || null,
    };
    if (!packIds.has(packId)) fail(`${where}: Pack ID '${packId}' isn't on the Course tab.`);
    if (!ID_RE.test(q.id)) fail(`${where}: Question ID '${q.id}' must be lowercase letters, digits and dashes.`);
    if (seenIds.has(q.id)) fail(`${where}: duplicate Question ID '${q.id}'.`);
    seenIds.add(q.id);
    if (!q.question) fail(`${where}: question '${q.id}' has no Question text.`);
    if (!q.correct) fail(`${where}: question '${q.id}' has no Correct Answer.`);
    if (q.wrong.some((w) => !w)) fail(`${where}: question '${q.id}' needs all three Wrong answers.`);
    const all = [q.correct, ...q.wrong].map((s) => s.toLowerCase());
    if (new Set(all).size !== 4) fail(`${where}: question '${q.id}' has duplicate options.`);
    if (TRIVIA_RE.test(q.question)) fail(`${where}: question '${q.id}' asks for a verse/chapter/count — ask about the content instead.`);
    out.push(q);
  }
  return out;
}

function parseUiText(wb) {
  const out = {};
  for (const r of sheetToObjects(wb, "UI Text")) {
    const key = str(r["Key"]);
    if (!key) continue;
    const text = str(r["Text"]);
    if (!UI_KEY_RE.test(key)) fail(`UI Text row ${r.__row}: key '${key}' isn't a dotted identifier.`);
    if (key in out) fail(`UI Text row ${r.__row}: duplicate key '${key}'.`);
    if (!text) fail(`UI Text row ${r.__row}: key '${key}' has no Text.`);
    out[key] = text;
  }
  return out;
}

function parseVideos(wb, readingIds) {
  if (!wb.Sheets["Videos"]) return [];
  const seen = new Set();
  const out = [];
  for (const r of sheetToObjects(wb, "Videos")) {
    const id = str(r["Video ID"]);
    if (!id) continue;
    const where = `Videos row ${r.__row}`;
    const v = {
      id,
      title: str(r["Title"]),
      packId: str(r["Reading ID"]),
      position: str(r["Position"]).toLowerCase() || "after",
      duration: str(r["Duration (m:ss)"]),
      streamUrl: str(r["Stream URL"]),
      visible: visibleCol(r["Visible?"]),
    };
    if (!ID_RE.test(id)) fail(`${where}: Video ID '${id}' must be lowercase letters, digits and dashes.`);
    if (seen.has(id)) fail(`${where}: duplicate Video ID '${id}'.`);
    seen.add(id);
    if (!v.title) fail(`${where}: video '${id}' has no Title.`);
    if (!readingIds.has(v.packId)) fail(`${where}: Reading ID '${v.packId}' isn't a reading on the Course tab.`);
    if (!["section", "before", "after"].includes(v.position)) fail(`${where}: Position must be "section", "before" or "after".`);
    const m = /^(\d+):([0-5]\d)$/.exec(v.duration);
    if (!m) fail(`${where}: Duration '${v.duration}' must look like 2:47.`);
    v.seconds = m ? Number(m[1]) * 60 + Number(m[2]) : 0;
    if (v.streamUrl && !/^https:\/\//.test(v.streamUrl)) fail(`${where}: Stream URL must start with https://.`);
    if (v.visible) {
      if (!v.streamUrl && !existsSync(path.join(VIDEO_DIR, `${id}.mp4`)))
        fail(`${where}: no media/videos/${id}.mp4 (or fill in Stream URL).`);
      if (!existsSync(path.join(POSTER_DIR, `${id}.jpg`))) fail(`${where}: no media/videos/posters/${id}.jpg.`);
    }
    out.push(v);
  }
  return out;
}

// ---- renderers ---------------------------------------------------------------

function renderCourseTs(packs, questionsByPack) {
  const packEntries = packs
    .map((p) => {
      const lines = [
        "  {",
        `    id: "${esc(p.id)}",`,
        `    title: "${esc(p.title)}",`,
        `    description: "${esc(p.description)}",`,
        `    category: "${p.category}",`,
        `    color: "${esc(p.color)}",`,
        `    visible: ${p.visible},`,
        `    questionIds: [${(questionsByPack[p.id] || []).map((q) => `"${esc(q.id)}"`).join(", ")}],`,
      ];
      if (p.reading) {
        lines.push(
          `    reading: {`,
          `      title: "${esc(p.reading.title)}",`,
          `      docId: "${p.reading.docId}",`,
          `      chapterIds: [\n${p.reading.chapterIds.map((c) => `        "${esc(c)}",`).join("\n")}\n      ],`,
          `      subtitle: "${esc(p.reading.subtitle)}",`,
          `    },`
        );
      }
      lines.push("  },");
      return lines.join("\n");
    })
    .join("\n");

  // Home layout: sections (in row order) → sub-headings → visible packs.
  const sections = [];
  for (const p of packs.filter((x) => x.visible)) {
    let s = sections[sections.length - 1];
    if (!s || s.title !== p.section) {
      s = { title: p.section, category: p.category, groups: [] };
      sections.push(s);
    }
    let g = s.groups[s.groups.length - 1];
    const gTitle = p.subsection || null;
    if (!g || g.title !== gTitle) {
      g = { title: gTitle, packIds: [] };
      s.groups.push(g);
    }
    g.packIds.push(p.id);
  }
  const courseEntries = sections
    .map(
      (s) =>
        `  {\n    title: "${esc(s.title)}",\n    category: "${s.category}",\n    groups: [\n` +
        s.groups
          .map((g) => `      { title: ${g.title ? `"${esc(g.title)}"` : "null"}, packIds: [${g.packIds.map((id) => `"${id}"`).join(", ")}] },`)
          .join("\n") +
        `\n    ],\n  },`
    )
    .join("\n");

  return (
    BANNER +
    `import type { CourseSection, Pack } from "./types";\n\n` +
    `/** Every row of the Course tab, in order. */\n` +
    `export const PACKS: Pack[] = [\n${packEntries}\n];\n\n` +
    `export const PACKS_BY_ID: Record<string, Pack> = Object.fromEntries(PACKS.map((p) => [p.id, p]));\n\n` +
    `/** Home: headings, sub-headings and the (visible) packs under each. */\n` +
    `export const COURSE: CourseSection[] = [\n${courseEntries}\n];\n`
  );
}

function renderQuestionsTs(questions) {
  const body = questions
    .map((q) => {
      const lines = [
        "  {",
        `    id: "${esc(q.id)}",`,
        `    packId: "${esc(q.packId)}",`,
        `    question: "${esc(q.question)}",`,
        `    correct: "${esc(q.correct)}",`,
        `    wrong: [${q.wrong.map((w) => `"${esc(w)}"`).join(", ")}],`,
      ];
      if (q.explanation) lines.push(`    explanation: "${esc(q.explanation)}",`);
      if (q.ref) lines.push(`    ref: "${esc(q.ref)}",`);
      lines.push("  },");
      return lines.join("\n");
    })
    .join("\n");
  return (
    BANNER +
    `import type { Question } from "./types";\n` +
    `import { PACKS_BY_ID } from "./course";\n\n` +
    `// ${questions.length} multiple-choice questions, in pack order.\n` +
    `export const QUESTIONS: Question[] = [\n${body}\n];\n\n` +
    `export const QUESTIONS_BY_ID: Record<string, Question> = Object.fromEntries(QUESTIONS.map((q) => [q.id, q]));\n\n` +
    `/** A pack's questions, in spreadsheet order. */\n` +
    `export function getQuestionsForPack(packId: string): Question[] {\n` +
    `  return (PACKS_BY_ID[packId]?.questionIds ?? []).map((id) => QUESTIONS_BY_ID[id]);\n` +
    `}\n`
  );
}

function renderVideosTs(videos) {
  const body = videos
    .filter((v) => v.visible)
    .map((v) =>
      [
        "  {",
        `    id: "${esc(v.id)}",`,
        `    title: "${esc(v.title)}",`,
        `    packId: "${esc(v.packId)}",`,
        `    position: "${v.position}",`,
        `    duration: ${v.seconds},`,
        v.streamUrl ? `    source: { uri: "${esc(v.streamUrl)}" },` : `    source: require("../../media/videos/${v.id}.mp4"),`,
        `    poster: require("../../media/videos/posters/${v.id}.jpg"),`,
        "  },",
      ].join("\n")
    )
    .join("\n");
  return (
    BANNER +
    `import type { Video } from "./types";\n\n` +
    `// Shown on Home before or after their reading, in this order.\n` +
    `export const VIDEOS: Video[] = [\n${body}\n];\n\n` +
    `export const VIDEOS_BY_ID: Record<string, Video> = Object.fromEntries(VIDEOS.map((v) => [v.id, v]));\n\n` +
    `/** A reading's videos on Home: introducing its whole section, just before it, or after it (review). */\n` +
    `export function getVideosForReading(packId: string, position: Video["position"]): Video[] {\n` +
    `  return VIDEOS.filter((v) => v.packId === packId && v.position === position);\n` +
    `}\n`
  );
}

function renderUiText(ui) {
  const body = Object.entries(ui)
    .map(([k, v]) => `  "${esc(k)}": "${esc(v)}",`)
    .join("\n");
  return BANNER + `export const UI_TEXT: Record<string, string> = {\n${body}\n};\n`;
}

function main() {
  if (!existsSync(XLSX_PATH)) {
    console.error(`No ${XLSX_NAME} at ${XLSX_PATH} — skipping content generation.`);
    process.exit(0);
  }
  const wb = XLSX.readFile(XLSX_PATH);
  const chapters = loadDocumentChapters();
  const packs = parseCourse(wb, chapters);
  const packIds = new Set(packs.map((p) => p.id));
  const readingIds = new Set(packs.filter((p) => p.reading).map((p) => p.id));
  const questions = parseQuestions(wb, packIds);
  const ui = parseUiText(wb);
  const videos = parseVideos(wb, readingIds);
  const questionsByPack = {};
  for (const q of questions) (questionsByPack[q.packId] ||= []).push(q);
  for (const p of packs) if (p.visible && !(questionsByPack[p.id] || []).length) fail(`Pack '${p.id}' has no questions.`);

  if (errors.length) {
    console.error(`${XLSX_NAME} has ${errors.length} problem(s):\n  - ${errors.join("\n  - ")}`);
    process.exit(1);
  }

  const outputs = new Map([
    [COURSE_TS, renderCourseTs(packs, questionsByPack)],
    [QUESTIONS_TS, renderQuestionsTs(questions)],
    [UI_TEXT_TS, renderUiText(ui)],
    [VIDEOS_TS, renderVideosTs(videos)],
  ]);
  const isGenerated = (f) => existsSync(f) && readFileSync(f, "utf8").startsWith(GENERATED_MARKER);
  const legacyDirFiles = existsSync(LEGACY_DIR) ? readdirSync(LEGACY_DIR).map((f) => path.join(LEGACY_DIR, f)) : [];
  const stale = [...LEGACY, ...legacyDirFiles].filter(isGenerated);
  const changed = [...outputs].filter(([f, content]) => !existsSync(f) || readFileSync(f, "utf8") !== content);

  if (CHECK_ONLY) {
    if (changed.length || stale.length) {
      console.error(`Generated content is out of date (${changed.length + stale.length} file(s)). Run: npm run sync-content`);
      process.exit(1);
    }
    console.log(`Generated content matches ${XLSX_NAME}.`);
    return;
  }

  for (const [f, content] of changed) writeFileSync(f, content);
  for (const f of stale) unlinkSync(f);
  if (existsSync(LEGACY_DIR) && readdirSync(LEGACY_DIR).length === 0) rmdirSync(LEGACY_DIR);

  if (changed.length || stale.length) {
    console.log(
      `Content synced: ${packs.length} packs (${readingIds.size} readings), ${questions.length} questions, ` +
        `${Object.keys(ui).length} UI strings, ${videos.filter((v) => v.visible).length} videos ` +
        `(${changed.length} file(s) written, ${stale.length} removed).`
    );
  } else {
    console.log(`Content already matches ${XLSX_NAME} — nothing to do.`);
  }
}

main();
